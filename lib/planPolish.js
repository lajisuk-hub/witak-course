/** 글자덩이(<hp:t>) 하나에 규칙을 적용한다 */
export function applyPolish(text, rules) {
  let out = text;
  for (const r of rules) {
    if (r.exact) {
      if (out.trim() === r.from) out = out.replace(r.from, r.to);
    } else if (out.includes(r.from)) {
      out = out.split(r.from).join(r.to);
    }
  }
  return out;
}

/**
 * 연간놀이계획안 조각(원본 XML)의 글자만 다듬는다.
 *
 * ★ 중요(과거 교훈): 글자 길이가 바뀌면 문단에 들어 있는 줄 정보(linesegarray)와 어긋나
 *   한글이 파일을 열지 못한다. 그래서 글자를 고친 조각에서는 linesegarray 를 통째로 뺀다.
 *   (한글이 열 때 다시 계산한다)
 */
export function polishBlock(xml, ageKey) {
  const rules = [...(POLISH_BY_AGE[ageKey] || []), ...POLISH_ALL];
  let changed = false;
  const out = xml.replace(/<hp:t>([\s\S]*?)<\/hp:t>/g, (whole, inner) => {
    // 태그(줄바꿈 등)가 섞인 글자덩이는 건드리지 않는다
    if (inner.includes('<')) return whole;
    const next = applyPolish(inner, rules);
    if (next === inner) return whole;
    changed = true;
    return `<hp:t>${next}</hp:t>`;
  });
  if (!changed) return xml;
  return (
    out
      .replace(/<hp:linesegarray>[\s\S]*?<\/hp:linesegarray>/g, '')
      // 글자를 비운 자리에 남는 빈 줄을 없앤다 (뒤에 다른 문단이 있을 때만 — 칸이 비면 안 되므로)
      .replace(
        /<hp:p [^>]*>\s*<hp:run charPrIDRef="\d+"><hp:t><\/hp:t><\/hp:run>\s*<\/hp:p>(?=\s*<hp:p )/g,
        ''
      )
  );
}
